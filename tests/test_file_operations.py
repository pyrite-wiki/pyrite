# --- the test's own frontmatter span, checked against the reader ------------


def span_of(text: str) -> FrontmatterSpan | None:
    """Where ``text``'s YAML frontmatter is: the caller's job in production
    (the one-frontmatter-splitter theme will own it). Checked against the
    reader's split so this helper cannot drift from it unnoticed."""
    at = 1 if text.startswith("﻿") else 0
    if not text.startswith("---", at):
        return None
    start = text.index("\n", at) + 1
    pos = start
    while pos < len(text):
        nl = text.find("\n", pos)
        line_end = len(text) if nl == -1 else nl + 1
        if text[pos:line_end].rstrip() == "---":
            span = FrontmatterSpan(start, pos, line_end)
            try:
                parsed = _frontmatter_of(text)
            except FrontmatterError:  # duplicate keys: the reader refuses
                return span
            assert parsed is not None
            assert parsed[1] == text[line_end:].strip()
            return span
        pos = line_end
    return None


def run(text: str, *ops: Any):
    return apply(text, list(ops), span_of(text))


# --- the independent oracle --------------------------------------------------


def _eq(a: Any, b: Any) -> bool:
    """ADR-0042 decision 3, written again from the ADR, for the oracle."""
    if isinstance(a, bool) or isinstance(b, bool):
        return type(a) is bool and type(b) is bool and a == b
    if a is None or b is None:
        return a is None and b is None
    if isinstance(a, int | float) and isinstance(b, int | float):
        return a == b
    if isinstance(a, str) and isinstance(b, date | datetime):
        a, b = b, a
    if isinstance(a, date | datetime) and isinstance(b, str):
        if a.isoformat() == b or (isinstance(a, datetime) and a.isoformat(" ") == b):
            return True
        if isinstance(a, datetime):
            try:
                other = datetime.fromisoformat(b)
            except ValueError:
                return False
            if (a.tzinfo is None) != (other.tzinfo is None):
                return False
            return a == other
        return False
    if isinstance(a, dict) and isinstance(b, dict):
        return set(a) == set(b) and all(_eq(a[k], b[k]) for k in a)
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(_eq(x, y) for x, y in zip(a, b, strict=True))
    if type(a) is not type(b) and not (isinstance(a, str) and isinstance(b, str)):
        return False
    return a == b


def _plain(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(k): _plain(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_plain(v) for v in value]
    if type(value).__name__ == "ScalarBoolean":
        return bool(value)
    if isinstance(value, datetime) and type(value) is not datetime:
        # ruamel's TimeStamp loses its tzinfo under copy.deepcopy
        return datetime.fromisoformat(value.isoformat())
    return value


def _reader(text: str) -> tuple[dict, str]:
    parsed = _frontmatter_of(text)
    assert parsed is not None, "the reader finds no frontmatter in the result"
    return _plain(dict(parsed[0])), parsed[1]


def _segments(path: Any) -> list:
    if isinstance(path, tuple | list):
        return list(path)
    out: list = []
    for part in path.split("."):
        name, _, rest = part.partition("[")
        if name:
            out.append(name)
        while rest:
            index, _, rest = rest.partition("]")
            out.append(int(index))
            rest = rest[1:] if rest.startswith("[") else rest
    return out


def _expected(meta: dict, op: Any) -> dict:
    """The operation applied to the parsed value, by hand."""
    import copy

    result = copy.deepcopy(meta)
    if isinstance(op, ReplaceBody):
        return result
    segs = _segments(op.path)
    if isinstance(op, AddSubkey):
        segs = [*segs, op.key]
    parent: Any = result
    for seg in segs[:-1]:
        if isinstance(parent, dict) and (seg not in parent or parent[seg] is None):
            if isinstance(op, Unset | Remove):
                return result
            parent[seg] = {}
        parent = parent[seg]
    last = segs[-1]
    if isinstance(op, Set | AddSubkey):
        if isinstance(parent, dict) and last in parent and _eq(parent[last], op.value):
            return result
        parent[last] = op.value
    elif isinstance(op, Unset):
        if isinstance(parent, dict):
            parent.pop(last, None)
        else:
            del parent[last]
    elif isinstance(op, Append):
        if parent.get(last) is None:
            parent[last] = []
        parent[last].append(op.value)
    elif isinstance(op, Remove):
        items = parent.get(last) or []
        for i, item in enumerate(items):
            if _eq(item, op.value):
                del items[i]
                break
    return result


def _key_blocks(text: str) -> dict[str, str]:
    """Each top-level key's own lines, by a line scan: a key line starts at
    column 0 and is not a comment or a list item; its block runs to the next
    key line, less trailing blank and comment-only lines."""
    span = span_of(text)
    assert span is not None
    lines = text[span.start : span.end].splitlines(keepends=True)
    blocks: dict[str, list[str]] = {}
    current = None
    for line in lines:
        head = line[:1]
        if head and head not in " \t#-\r\n" and ":" in line:
            current = line.split(":", 1)[0].strip().strip("'\"")
            blocks[current] = [line]
        elif current is not None:
            blocks[current].append(line)
    out = {}
    for key, block in blocks.items():
        while len(block) > 1 and (not block[-1].strip() or block[-1].lstrip().startswith("#")):
            block = block[:-1]
        out[key] = "".join(block)
    return out


def _top(op: Any) -> str | None:
    if isinstance(op, ReplaceBody):
        return None
    return str(_segments(op.path)[0])


def check_contract(before: str, ops: list, after: str) -> None:
    """Properties 1 and 3 for any result: untouched top-level keys are
    byte-identical; the reader gets exactly the operations applied; key order
    holds with new keys last; prefix (BOM), body and line endings are kept."""
    named = {_top(op) for op in ops}
    old_blocks, new_blocks = _key_blocks(before), _key_blocks(after)
    for key, block in old_blocks.items():
        if key not in named:
            assert new_blocks.get(key) == block, f"untouched key {key!r} changed"
    meta, body = _reader(before)
    expected = meta
    for op in ops:
        expected = _expected(expected, op)
    got, new_body = _reader(after)
    assert _eq(got, expected), f"parsed {got!r}, expected {expected!r}"
    assert list(got) == list(expected), "key order changed"
    if not any(isinstance(op, ReplaceBody) for op in ops):
        assert after[span_of(after).body :] == before[span_of(before).body :]
    assert after.startswith("﻿") == before.startswith("﻿")
    if "\r\n" in before:
        assert after.count("\n") == after.count("\r\n"), "a bare LF in a CRLF file"
    else:
        assert "\r" not in after


