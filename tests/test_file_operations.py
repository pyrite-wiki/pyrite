# --- the post-check is the guard (ADR-0042 decision 2) ------------------------


def test_a_narrow_edit_that_fails_the_post_check_is_widened_not_returned(monkeypatch):
    """A narrow edit that also changes bytes it was not asked to change must
    never be returned: the post-check catches it and the key is widened
    item-wise (or the call refuses)."""
    from pyrite.storage import file_operations as fo

    real = fo._narrow_edits

    def corrupt(doc, op):
        edits = real(doc, op)
        # also respell an untouched key: `type: note` -> `type: Note`
        at = doc.text.index("type: note") + len("type: ")
        return [*edits, (at, at + 1, "N")]

    monkeypatch.setattr(fo, "_narrow_edits", corrupt)
    before = SHAPES["doc-field-notes"]
    try:
        after, report = run(before, Append("links", {"target": "x"}))
    except OperationRefusedError:
        return
    assert "type: note\n" in after
    check_contract(before, [Append("links", {"target": "x"})], after)
    assert report.widened == ("links",)


def test_a_narrow_edit_that_breaks_the_value_is_widened(monkeypatch):
    """The post-check compares values too, not only untouched bytes."""
    from pyrite.storage import file_operations as fo

    real = fo._narrow_edits

    def corrupt(doc, op):
        return [(s, e, r.replace("bar", "baz")) for s, e, r in real(doc, op)]

    monkeypatch.setattr(fo, "_narrow_edits", corrupt)
    before = SHAPES["doc-legacy-links"]
    op = Append("links", {"target": "bar", "relation": "related"})
    after, report = run(before, op)
    check_contract(before, [op], after)
    assert report.widened == ("links",)
    # item-wise: the hand-written item, comment and all, is copied by bytes
    assert _diff(before, after) == ["+- target: bar\n", "+  relation: related\n"]


