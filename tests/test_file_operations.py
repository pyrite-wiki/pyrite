@pytest.mark.parametrize(
    ("shape", "ops", "outcome"),
    CASES,
    ids=[f"{s}-{i}" for i, (s, _, _) in enumerate(CASES)],
)
def test_operation_contract(shape, ops, outcome):
    before = SHAPES[shape]
    if outcome == "refused":
        with pytest.raises(OperationRefusedError) as raised:
            run(before, *ops)
        assert raised.value.reason
        return
    after, report = run(before, *ops)
    if outcome == "unchanged":
        assert after is before
        assert not report.changed
        assert [r.outcome for r in report.results] == ["unchanged"] * len(ops)
        return
    assert after != before
    assert report.changed
    check_contract(before, ops, after)


