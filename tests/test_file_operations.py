def _ruamel_keys(text: str) -> list:
    from pyrite.utils.yaml import load_yaml

    span = span_of(text)
    keys: list = []

    def walk(node: Any) -> None:
        if isinstance(node, dict):
            for k, v in node.items():
                keys.append(k)
                walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)

    walk(load_yaml(text[span.start : span.end]))
    return keys


