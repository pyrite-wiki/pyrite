# --- the oracle can see failures: candidate A as a control --------------------


def _round_trip(text: str, key: str, value: Any) -> str:
    """#730's candidate A: load with ruamel, set, dump. Rejected by the spike
    for respelling bytes nobody asked to change."""
    from pyrite.utils.yaml import dump_yaml, load_yaml

    span = span_of(text)
    data = load_yaml(text[span.start : span.end])
    data[key] = value
    return text[: span.start] + dump_yaml(data) + text[span.end :]


@pytest.mark.parametrize(
    ("shape", "key", "value"),
    [
        ("hugo", "draft", True),  # re-indents the 4-space params map
        ("yaml11-words", "status", "done"),  # respells `nil: null` as `nil:`
        ("odd-spacing", "title", "New"),  # collapses `id:    odd`
    ],
)
def test_the_oracle_catches_the_round_trip(shape, key, value):
    """The contract check is not vacuous: the round trip fails it where the
    spike saw it change untouched bytes, and apply passes it."""
    before = SHAPES[shape]
    with pytest.raises(AssertionError):
        check_contract(before, [Set(key, value)], _round_trip(before, key, value))
    after, _ = run(before, Set(key, value))
    check_contract(before, [Set(key, value)], after)
