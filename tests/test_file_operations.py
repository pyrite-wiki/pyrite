"""``apply(text, ops, span)``: operations on an entry file's text (ADR-0042 P1).

ADR-0042 decisions 1, 2, 3 and 6, amendment A4; #730 section 1 and phase P1.
The function is pure and not wired to any write path yet (P3 does that).

The fixtures are the 17 hand-made shapes of #730 section 1, written here by
hand as string literals, never generated by Pyrite. They are string literals
rather than files because several shapes are bytes the repo's pre-commit hooks
would "fix" in a file: CRLF, a BOM, trailing spaces, a body with no final
newline.

The oracle is independent of the module under test:

- the reader parses before and after (``load_frontmatter``, the split every read
  uses);
- the expected value is the operations applied to the parsed dict by
  ``_expected`` below;
- the bytes outside the spans an operation names are compared, before against
  after, by ``tests/file_operations_oracle.py``: its own span rule and its own
  mechanism (an indentation scan for where block values end), never the
  module's (Andon #745: an earlier oracle here was the module's scan copied);
- equality is ``_eq``, ADR-0042 decision 3 written out again here.

Each guard the module adds has a test that fails when that guard alone is
removed. They are listed in the PR.
"""

