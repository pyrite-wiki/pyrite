def _diff(before: str, after: str) -> list[str]:
    import difflib

    a, b = before.splitlines(keepends=True), after.splitlines(keepends=True)
    return [
        line
        for line in difflib.unified_diff(a, b, n=0)
        if line[:1] in "+-" and not line.startswith(("+++", "---"))
    ]


