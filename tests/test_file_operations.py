def test_every_shape_is_in_the_table():
    """Property 7: each of #730's 17 shapes is exercised."""
    assert len(SHAPES) == 17
    assert {shape for shape, _, _ in CASES} == set(SHAPES)


@pytest.mark.parametrize(
    ("shape", "ops", "outcome"),
    CASES,
    ids=[f"{s}-{i}" for i, (s, _, _) in enumerate(CASES)],
)
def test_operation_contract(shape, ops, outcome):
    before = SHAPES[shape]
    if outcome == "refused":
        with pytest.raises(OperationRefusedError) as raised:
            run(before, *ops)
        assert raised.value.reason
        return
    after, report = run(before, *ops)
    if outcome == "unchanged":
        assert after is before
        assert not report.changed
        assert [r.outcome for r in report.results] == ["unchanged"] * len(ops)
        return
    assert after != before
    assert report.changed
    check_contract(before, ops, after)


# --- exact bytes: quote style, comment column, EOL, BOM, list style -----------


def _diff(before: str, after: str) -> list[str]:
    import difflib

    a, b = before.splitlines(keepends=True), after.splitlines(keepends=True)
    return [
        line
        for line in difflib.unified_diff(a, b, n=0)
        if line[:1] in "+-" and not line.startswith(("+++", "---"))
    ]


