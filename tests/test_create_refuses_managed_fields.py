def _any(_form):
    return True


def _task_only(etype):
    return etype == "task"


#: path -> (function, which forms it can send, which types it can send)
PATHS = {
    "service.create": (p_service_create, _any, lambda t: True),
    "service.create_entry": (p_service_create_entry, _any, lambda t: True),
    "service.bulk_create_entries": (p_service_bulk, _any, lambda t: True),
    "mcp.kb_create": (p_mcp_create, _any, lambda t: True),
    "mcp.kb_bulk_create": (p_mcp_bulk, _any, lambda t: True),
    "cli.create -f": (p_cli_create, _any, lambda t: True),
    "rest.post": (p_rest_post, _any, lambda t: True),
    "cli.task create --field": (p_cli_task_create, _any, _task_only),
    "journalism.create_entity": (p_journalism_entity, _any, lambda t: t == "note"),
}


def _grid():
    cells = []
    for path, (_fn, forms_ok, types_ok) in PATHS.items():
        for etype, field in CELLS:
            if not types_ok(etype):
                continue
            for label, extra in _forms(etype, field):
                if not forms_ok(label):
                    continue
                marks = []
                if label.startswith("envelope:"):
                    marks.append(ENVELOPE_CONTROL)
                elif field == "id" and label.startswith("dotted:"):
                    marks.append(
                        pytest.mark.control(
                            reason="metadata.id was already refused: id spelled twice"
                        )
                    )
                elif path == "cli.task create --field" and label.startswith("top:"):
                    marks.append(
                        pytest.mark.control(
                            reason="task create refused these by its own list; now by the service"
                        )
                    )
                cells.append(
                    pytest.param(
                        path, etype, field, extra, id=f"{path}|{etype}.{field}|{label}", marks=marks
                    )
                )
    return cells


@pytest.mark.parametrize(("path", "etype", "field", "extra"), _grid())
def test_a_create_path_refuses_a_managed_field(env, path, etype, field, extra):
    before = _md_files(env)
    refused, text = PATHS[path][0](env, etype, extra)
    assert refused, text
    assert field in text, text
    assert _md_files(env) == before, "refused, yet a file appeared"


#: Import paths drop what an export adds and a type manages, and name each key
#: under ``ignored`` (the maintainer's decision, 2026-10-20); a direct create
#: refuses it. Same cells, the other oracle.
IMPORT_PATHS = {"cli.import": p_cli_import, "rest.import": p_rest_import}


def _import_grid():
    cells = []
    for path in IMPORT_PATHS:
        for etype, field in CELLS:
            if field == "id":
                continue  # the entry's identity is kept by an import, not dropped
            for label, extra in _forms(etype, field):
                marks = []
                cells.append(
                    pytest.param(
                        path, etype, field, extra, id=f"{path}|{etype}.{field}|{label}", marks=marks
                    )
                )
    return cells


@pytest.mark.parametrize(("path", "etype", "field", "extra"), _import_grid())
def test_an_import_path_drops_a_managed_field_and_reports_it(env, path, etype, field, extra):
    n = next(_TITLES)
    title = f"Imp{n}"
    ok, text = IMPORT_PATHS[path](env, etype, extra, title)
    written = list(env["kb_path"].rglob(f"imp{n}.md"))
    assert ok and len(written) == 1, text
    assert field in text, text  # named under ignored
    # The sent value is not in the file (an ADR's model writes its own default
    # adr_number: the forged one must not appear).
    sent = re.compile(rf"^\s*(metadata\.)?{field}:\s*[\"']?x[\"']?\s*$", re.M)
    assert not sent.search(written[0].read_text()), written[0].read_text()


def test_an_alias_of_a_managed_field_is_refused_at_every_spelling(env):
    """An alias folds to its target (ADR-0051): declare `log` for task's
    `status_change_log` the way a plugin would, and every spelling is refused.
    Red if the create check stopped resolving through `field_at`."""
    from pyrite.schema import field_aliases as fa

    real = fa.field_aliases

    def with_log(type_name, *a, **kw):
        out = dict(real(type_name, *a, **kw))
        if type_name == "task":
            out["log"] = "status_change_log"
        return out

    for extra in (
        {"log": [{"x": 1}]},
        {"metadata.log": [{"x": 1}]},
        {"metadata": {"log": [{"x": 1}]}},
    ):
        with patch.object(fa, "field_aliases", with_log):
            refused, text = p_service_create(env, "task", extra)
        assert refused and "status_change_log" in text, (extra, text)


