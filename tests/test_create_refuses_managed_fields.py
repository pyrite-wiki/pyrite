def _md_files(env):
    return sorted(str(p.relative_to(env["kb_path"])) for p in env["kb_path"].rglob("*.md"))


def _cli(env, args):
    with (
        patch("pyrite.cli.load_config", return_value=env["config"]),
        patch("pyrite.cli.context.load_config", return_value=env["config"]),
    ):
        return runner.invoke(cli_app, args)


def _with_svc(env, fn):
    db = PyriteDB(env["db_path"])
    try:
        return fn(KBService(env["config"], db))
    finally:
        db.close()


def _raised(fn) -> tuple[bool, str]:
    try:
        out = fn()
    except PyriteError as e:
        return True, str(e)
    return False, str(out)


