#: (entry type, managed field). ``id`` and ``kb_name`` have no top-level spelling
#: on a create (``id`` is the entry's id; ``kb_name`` is the call's own argument).
CELLS = [
    ("task", "status_change_log"),
    ("task", "evidence"),
    ("task", "agent_context"),
    ("task", "assigned_at"),
    ("adr", "adr_number"),
    ("note", "file_path"),
    ("note", "provenance"),
    ("note", "extra_frontmatter"),
    ("note", "id"),
    ("note", "kb_name"),
]
NO_TOP_LEVEL = {"id", "kb_name"}

ENVELOPE_CONTROL = pytest.mark.control(
    reason="the metadata envelope was already refused (#1001 decision 6); only the other spellings were open"
)


def _forms(etype: str, field: str) -> list[tuple[str, dict]]:
    """Every request-side spelling of ``field``: (label, extra keys of the spec)."""
    cls = get_entry_class(etype)
    out: list[tuple[str, dict]] = []
    for path in spellings_of(cls, etype, field):
        if len(path) == 1:
            if field in NO_TOP_LEVEL and path[0] == field:
                continue
            out.append((f"top:{path[0]}", {path[0]: "x"}))
        else:
            out.append((f"envelope:{path[1]}", {"metadata": {path[1]: "x"}}))
            out.append((f"dotted:{path[1]}", {f"metadata.{path[1]}": "x"}))
    return out


