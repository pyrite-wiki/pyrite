def _spec(etype, extra, title="T1"):
    return {"entry_type": etype, "title": title, **extra}


def p_service_create(env, etype, extra):
    return _raised(lambda: _with_svc(env, lambda s: s.create(KB, _spec(etype, extra))))


def p_service_create_entry(env, etype, extra):
    return _raised(
        lambda: _with_svc(env, lambda s: s.create_entry(KB, "t1", "T1", etype, "", **extra))
    )


def p_service_bulk(env, etype, extra):
    def run(s):
        (res,) = s.bulk_create_entries(KB, [_spec(etype, extra)])
        if not res.get("created"):
            raise ValidationError(res.get("error", "refused"))
        return res

    return _raised(lambda: _with_svc(env, run))


def p_mcp_create(env, etype, extra):
    from pyrite.server.mcp_server import PyriteMCPServer

    server = PyriteMCPServer(env["config"], tier="admin")
    try:
        res = server._dispatch_tool("kb_create", {"kb_name": KB, **_spec(etype, extra)})
    finally:
        server.close()
    return (not res.get("created")), json.dumps(res)


def p_mcp_bulk(env, etype, extra):
    from pyrite.server.mcp_server import PyriteMCPServer

    server = PyriteMCPServer(env["config"], tier="admin")
    try:
        res = server._dispatch_tool(
            "kb_bulk_create", {"kb_name": KB, "entries": [_spec(etype, extra)]}
        )
    finally:
        server.close()
    return (not res["results"][0].get("created")), json.dumps(res)


def _cli_pairs(extra):
    args = []
    for k, v in extra.items():
        args += ["-f", f"{k}={json.dumps(v) if isinstance(v, dict) else v}"]
    return args


def p_cli_create(env, etype, extra):
    res = _cli(env, ["create", "-k", KB, "-t", etype, "--title", "T1", *_cli_pairs(extra)])
    return res.exit_code != 0, res.output


def p_cli_task_create(env, etype, extra):
    args = []
    for k, v in extra.items():
        args += ["--field", f"{k}={json.dumps(v) if isinstance(v, dict) else v}"]
    res = _cli(env, ["task", "create", "-k", KB, "T1", *args])
    return res.exit_code != 0, res.output


