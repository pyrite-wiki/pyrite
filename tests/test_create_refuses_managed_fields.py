"""A create refuses a managed field at every spelling, on every create path (#1010).

The property: a field Pyrite or the type manages (``_MANAGED_FIELDS`` plus
``Entry.managed_fields``) is refused on create at every spelling ADR-0051
treats as the same field -- the top-level key, a dotted top-level key
(``metadata.status_change_log``), the key under ``metadata:``, and an alias
of the field (none is registered for a managed field today; a test declares
one) -- on every path that creates an entry from a caller's values. The
refusal names the field and no file is written. Two rules relax it: an
in-process owner sets its own field, and only the field it names
(``create_entry(..., owns=...)``); and an import drops and reports instead
(``test_import_drops_and_reports_managed.py``). ``pyrite add FILE`` adopts a
file's own values (pending the maintainer's explicit OK).

One test, ``test_a_create_path_refuses_a_managed_field``, is parametrised over
(path x spelling), the spellings generated by ``spellings_of``. A path is
registered in ``PATHS``; ``test_every_create_call_site_is_classified`` scans
``pyrite/`` and ``extensions/*/src`` for calls into the create pipeline and
fails when one is not classified in ``CALL_SITES``, so a new path cannot be
added without choosing: guarded by the grid, or safe by reading (and why).
"""

